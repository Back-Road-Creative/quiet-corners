# Flat, order-preserving view of every corridor waypoint with exact
# junction duplicates (cities shared by crossing routes) removed.
INTERSTATE_WAYPOINTS: list[tuple[float, float]] = list(
    dict.fromkeys(wp for chain in INTERSTATE_ROUTES.values() for wp in chain)
)


def _point_to_segment_miles(
    lat: float,
    lon: float,
    seg_a: tuple[float, float],
    seg_b: tuple[float, float],
) -> float:
    """Miles from (lat, lon) to the segment between seg_a and seg_b.

    Uses an equirectangular projection centred on the query point — a
    flat-earth approximation whose error is negligible at the sub-300-mile
    segment lengths and query distances that matter for scoring.
    """
    radius = DEFAULT_CONFIG.remoteness.earth_radius_miles
    cos_lat = math.cos(math.radians(lat))
    ax = math.radians(seg_a[1] - lon) * cos_lat * radius
    ay = math.radians(seg_a[0] - lat) * radius
    bx = math.radians(seg_b[1] - lon) * cos_lat * radius
    by = math.radians(seg_b[0] - lat) * radius
    dx, dy = bx - ax, by - ay
    seg_len_sq = dx * dx + dy * dy
    if seg_len_sq == 0.0:
        return math.hypot(ax, ay)
    # The query point is the origin; clamp its projection onto the segment.
    t = max(0.0, min(1.0, -(ax * dx + ay * dy) / seg_len_sq))
    return math.hypot(ax + t * dx, ay + t * dy)


def distance_to_nearest_interstate(lat: float, lon: float) -> float:
    """Compute minimum distance in miles from a point to any interstate corridor."""
    min_dist = float("inf")
    for chain in INTERSTATE_ROUTES.values():
        for seg_a, seg_b in zip(chain, chain[1:]):
            d = _point_to_segment_miles(lat, lon, seg_a, seg_b)
            if d < min_dist:
                min_dist = d
    return round(min_dist, 1)
